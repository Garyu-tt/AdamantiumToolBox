import {strict as assert} from 'node:assert';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {decodeWire} from './reader.mjs';
import {encodeWire} from './writer.mjs';

const cli=process.argv[2];
assert.ok(cli,'C++ Genome GA1a CLI is required');
const run=(mode,input)=>spawnSync(cli,[mode],{input,maxBuffer:16*1024*1024});
const emitted=run('emit');
assert.equal(emitted.status,0,emitted.stderr?.toString());
assert.ok(emitted.stdout.length>100);
const wire=emitted.stdout;
const genome=decodeWire(wire);
assert.equal(genome.rootGraph,'mas.program');
assert.equal(genome.genomeId,'adamantium.genome');
assert.equal(genome.lane,0);
assert.deepEqual(genome.chromosomes.map(c=>c.graphId),
  ['dante.brain','infra.policy','mas.program','mas.transform']);
const brain=genome.chromosomes[0];
const feedback=brain.genes.find(g=>g.kind===4 && g.payload.id==='feedback');
assert.equal(feedback.payload.semantics,3);
assert.equal(feedback.payload.delayTicks,2);
const policy=genome.chromosomes[1];
const grant=policy.genes.find(g=>g.kind===4);
assert.equal(grant.payload.semantics,5);
const program=genome.chromosomes[2];
const sub=program.genes.find(g=>g.kind===2 && g.payload.id==='sub');
assert.equal(sub.payload.graphRef,'mas.transform');
assert.equal(sub.payload.graphRefRevision,3n);
const decodedAndReencoded=encodeWire(genome);
assert.deepEqual(decodedAndReencoded,wire,'JS must reconstruct exact C++ bytes');
const nativeRead=run('read',decodedAndReencoded);
assert.equal(nativeRead.status,0,nativeRead.stderr?.toString());
assert.deepEqual(nativeRead.stdout,wire,'C++ must accept JS-generated stream');
const acquired={...genome,lane:1};
const acquiredBytes=encodeWire(acquired);
const acceptedAcquired=run('read',acquiredBytes);
assert.equal(acceptedAcquired.status,0);
assert.deepEqual(acceptedAcquired.stdout,acquiredBytes);
const badReserved=Buffer.from(wire);badReserved[9]=1;
assert.notEqual(run('read',badReserved).status,0);
const truncated=wire.subarray(0,wire.length-1);
assert.notEqual(run('read',truncated).status,0);
const extra=Buffer.concat([wire,Buffer.from([0])]);
assert.notEqual(run('read',extra).status,0);
assert.throws(()=>decodeWire(extra),/trailing_bytes/);
const fingerprint=createHash('sha256').update(wire).digest('hex');
assert.equal(fingerprint.length,64);
console.log('GENOME_GA1A_CPP_NODE_ROUNDTRIP_OK: bytes='+wire.length+
  ' sha256='+fingerprint+' four graphs, no grants or execution');
