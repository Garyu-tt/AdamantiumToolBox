import {strict as assert} from 'node:assert';
import {readFile} from 'node:fs/promises';
import {validateManifest} from '../core/contract.mjs';
import {initialize,features,suggest,feedback} from '../apps/mikoshi_prosody/network.mjs';
import {profile,voiceControls} from '../apps/mikoshi_voice/engine.mjs';
const m=JSON.parse(await readFile(new URL('../apps/mikoshi_prosody/manifest.json',import.meta.url)));
assert(validateManifest(m));assert.equal(m.id,'mikoshi_prosody');
assert.equal(features('Привет!').length,5);
assert.throws(()=>features(''),/invalid_utterance/);
let state=initialize();
const sentence='Привет! Я учусь говорить.';
const initial=suggest(state,sentence);
assert.equal(initial.observations,0);
for(let i=0;i<8;i++)state=feedback(state,sentence,'higher').state;
const after=suggest(state,sentence);
assert(after.pitchDelta>initial.pitchDelta,'MLP learns pitch corrections from feedback');
assert.equal(after.observations,8);
for(let i=0;i<8;i++)state=feedback(state,sentence,'slower').state;
assert(suggest(state,sentence).speedDelta<initial.speedDelta);
const good=feedback(state,sentence,'good');
assert.equal(good.updated,false);assert.equal(good.state.positive,1);
assert.throws(()=>feedback(state,sentence,'imitate_artist'),/invalid_feedback/);
assert.throws(()=>suggest({...state,w1:[]},sentence),/invalid_prosody_state/);
const base=profile(),snapshot=JSON.stringify(base);
const controls=voiceControls(base,{pitchDelta:5,speedDelta:-8});
assert.equal(controls.pitch,Math.min(99,base.pitch+5));
assert.equal(controls.speed,Math.max(80,base.speed-8));
assert.equal(JSON.stringify(base),snapshot,'voice identity is unaffected by learning');
assert.throws(()=>voiceControls(base,{pitchDelta:90}),/prosody_out_of_bounds/);
console.log('MIKOSHI_PROSODY_OK online MLP feedback, timbre anchor and MAS schema');
