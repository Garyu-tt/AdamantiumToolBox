import {strict as assert} from 'node:assert';
import {empty,decode,folder,pin,move,rename,remove,customItems,setPosition} from '../apps/desktop/state.js';
import {positionsFor,snapped,swapInto} from '../apps/desktop/icon_grid.js';
import {rootLinks,userFolder} from '../apps/desktop/user_tree.js';
const views=new Map([['editor.view',{title:'Editor'}],['browser.view',{title:'Browser'}]]);
const state=empty(),root=folder(state,'Tools'),nested=folder(state,'Development',root.id);
const shortcut=pin(state,'editor.view',root.id),browser=pin(state,'browser.view');
assert.equal(pin(state,'browser.view').id,browser.id);
assert(!move(state,root.id,nested.id),'cannot create recursive folders');
assert(move(state,shortcut.id,nested.id));
assert(!move(state,shortcut.id,'user:missing'));
assert(rename(state,root.id,'Utilities'));
assert.equal(customItems(state,null,views).length,2);
assert.equal(userFolder(state,root.id,views).children[0].children[0].view,'editor.view');
setPosition(state,browser.id,112,201);
const loaded=decode(JSON.stringify(state));
assert.equal(loaded.positions[browser.id].x,112);
assert.equal(loaded.items.find(x=>x.id===shortcut.id).parent,nested.id);
assert.equal(decode('{bad').items.length,0);
assert.equal(decode('{"schema":"wrong","items":[]}').items.length,0);
assert(!decode(JSON.stringify({...state,items:[{id:'__proto__',kind:'folder',name:'bad'}]})).items.length);
const cyclic=empty(),a=folder(cyclic,'A'),b=folder(cyclic,'B',a.id);
a.parent=b.id;
assert.equal(decode(JSON.stringify(cyclic)).items.find(x=>x.id===a.id).parent,null);
assert(remove(loaded,root.id));assert.equal(loaded.items.find(x=>x.id===nested.id).parent,null);
const base=rootLinks([{type:'folder',name:'Infra',children:[]},{type:'app',name:'Editor',view:'editor.view'}]);
assert(base.every(x=>x.id.startsWith('base:')));
const choices=[...base,{id:browser.id,type:'app'}];
const placed=positionsFor(choices,{},430,325);
assert.equal(Object.keys(placed).length,3);
assert.equal(new Set(Object.values(placed).map(v=>v.x+':'+v.y)).size,3);
assert.deepEqual(snapped({x:120,y:195},430,325),{x:112,y:212});
assert(swapInto(state,choices[2].id,placed[choices[0].id],placed,430,325));
assert.deepEqual(state.positions[choices[0].id],placed[choices[2].id]);
assert.deepEqual(state.positions[choices[2].id],placed[choices[0].id]);
console.log('DESKTOP_STATE_OK user folders nesting recovery placement and swaps');
