import {strict as assert} from 'node:assert';
import {synth} from '../apps/mikoshi_phonetics/synth.mjs';
import {segment} from '../apps/mikoshi_segments/segmenter.mjs';
import {shape,delta} from '../apps/mikoshi_segments/spectra.mjs';
const a=synth({f1:810,f2:1290}),i=synth({f1:300,f2:2450});
assert.equal(a.length,2400);
assert(delta(shape(a),shape(i))>.055,'distinct spectral shapes');
assert(delta(shape(a),shape(a))<1e-9);
const silence=n=>Array(n).fill(0);
const apart=segment([...silence(2400),...a,...silence(1200),...i,...silence(2400)]);
assert.equal(apart.detected,2,'two separated sounds must be distinct events');
assert.equal(apart.events.length,2);
assert(apart.events[1].timeMs>apart.events[0].timeMs);
assert(apart.events[1].gapMs>=250);
assert(apart.events.every(e=>e.samples.length===2400));
assert.equal(apart.retained,false);
const continuous=segment([...a,...i]);
assert.equal(continuous.detected,2,'spectral novelty separates joined sounds');
const repeated=segment([...a,...a]);
assert.equal(repeated.detected,1,'one stationary sound is not multiple syllables');
assert.equal(segment(silence(4800)).detected,0);
assert.throws(()=>segment([0,1]),/invalid_stream_audio/);
assert.throws(()=>segment(Array(50000).fill(.2)),/invalid_stream_audio/);
assert.throws(()=>segment(Array(4800).fill(2)),/invalid_stream_audio/);
assert.throws(()=>segment(Array(4800).fill(.2),48000),/invalid_stream_audio/);
console.log('MIKOSHI_SEGMENTS_OK activity, novelty, event timestamps and silence');
