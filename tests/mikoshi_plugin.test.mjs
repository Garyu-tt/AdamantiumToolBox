import {strict as assert} from 'node:assert';
import {readFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {validateManifest,validateGraph} from '../core/contract.mjs';
import {probePlugin} from '../standards/lifecycle/probe.mjs';

const root=resolve(fileURLToPath(new URL('../plugins/mikoshi/',import.meta.url)));
const manifest=JSON.parse(await readFile(join(root,'manifest.json'),'utf8'));
const mapping=JSON.parse(await readFile(join(root,'routes.json'),'utf8'));
assert(validateManifest(manifest));
assert.equal(manifest.id,'mikoshi');
assert.deepEqual(manifest.permissions,['mikoshi.read']);
assert.equal(mapping.schema,'mikoshi.mas.routes.v1');
assert(mapping.static.some(x=>x.id==='mikoshi.status'));
assert(mapping.static.every(x=>['local','get','native'].includes(x.mode)));
assert(mapping.static.every(x=>!(x.native||'').match(/restore|switch|step|accept|motor.write/)));
assert(mapping.dynamic.every(x=>x.fromPrefix.startsWith('visual2d.open.')));
assert.equal((await probePlugin(root,manifest,5000)).graph,'valid');
console.log('MIKOSHI_MAS_CONTRACT_OK signed-compatible independent probe');
