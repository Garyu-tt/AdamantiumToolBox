import {strict as assert} from 'node:assert';
import {ReliableSensoryBus} from '../sdk/dante/sensory_bus_reliable.mjs';
import {SENSORY_SCHEMA} from '../sdk/dante/sensory_bus.mjs';
const e=(sequence,source='cpu.world')=>({schema:SENSORY_SCHEMA,source,kind:'visual.frame',sequence,observedAtMs:sequence,payload:{distance:2}});
const b=new ReliableSensoryBus({capacity:2,maxEventBytes:256,maxSources:2});
assert.deepEqual(b.publish(e(0)),{ok:true});assert.deepEqual(b.publish(e(1)),{ok:true});
assert.deepEqual(b.publish(e(2)),{ok:false,reason:'backpressure'});
assert.deepEqual(b.peek().map(x=>x.sequence),[0,1]);assert.deepEqual(b.peek().map(x=>x.sequence),[0,1]);
assert.deepEqual(b.ack('cpu.world','visual.frame',0),{ok:true});
assert.deepEqual(b.publish(e(2)),{ok:true});
assert.deepEqual(b.ack('cpu.world','visual.frame',1),{ok:true});
assert.deepEqual(b.publish(e(0,'other.world')),{ok:true});
assert.deepEqual(b.publish(e(0,'third.world')),{ok:false,reason:'source_limit'});
const cycle={};cycle.self=cycle;
assert.deepEqual(b.publish({...e(3),payload:cycle}),{ok:false,reason:'invalid_event'});
assert.deepEqual(b.publish({...e(3),payload:{big:'x'.repeat(1000)}}),{ok:false,reason:'event_too_large'});
assert.deepEqual(b.publish({...e(3),payload:{value:Infinity}}),{ok:false,reason:'invalid_event'});
assert.equal(b.status().queued,2);
