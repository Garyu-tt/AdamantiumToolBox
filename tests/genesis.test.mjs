import {strict as assert} from 'node:assert';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {BrainStore} from '../apps/genesis/store.mjs';
import {validateGenome,summary,step,train,grow,integrate,retarget} from '../apps/genesis/brain.mjs';
import {discoverModules} from '../apps/genesis/registry.mjs';
import {validateGraph,validateManifest} from '../core/contract.mjs';
const base=fileURLToPath(new URL('../apps/genesis/',import.meta.url));
const manifest=JSON.parse(await readFile(join(base,'manifest.json'),'utf8'));
assert(validateManifest(manifest));
const {graph,actions}=await discoverModules(base,manifest);
assert(validateGraph(graph,manifest));
assert(actions.has('genesis.brains.grow')&&actions.has('genesis.brains.snapshot'));
assert.throws(()=>validateGenome({initial_neurons:500}),/budget/);
const root=await mkdtemp(join(tmpdir(),'genesis-test-'));
try{
 const store=new BrainStore(root);
 const brain=await store.create({initial_neurons:8,target_neurons:16,maximum_neurons:32});
 const ids=brain.neurons.map(n=>n.id);
 const a=await store.change(brain.id,b=>step(b,{stimulus:0.6,steps:10}));
 assert(Number.isFinite(a.output));
 await store.change(brain.id,b=>train(b,{target:0.9}));
 const before=summary(await store.load(brain.id),true);
 const expanded=await store.change(brain.id,b=>grow(b,{count:4}));
 assert.equal(expanded.neurons,12);
 assert.deepEqual((await store.load(brain.id)).neurons.slice(0,8).map(n=>n.id),ids);
 const after=summary(await store.load(brain.id),true);
 assert.deepEqual(after.readout.slice(0,8),before.readout.slice(0,8));
 assert.equal(after.shadow,4);
 await store.change(brain.id,b=>integrate(b,{count:4}));
 await store.change(brain.id,b=>retarget(b,{target_neurons:24}));
 assert.equal((await store.load(brain.id)).genome.target_neurons,24);
 const snap=await store.snapshot(brain.id);
 const clone=await store.fork(brain.id,snap.snapshotId);
 assert.notEqual(clone.id,brain.id);
 assert.equal(clone.parent.brainId,brain.id);
 assert.equal((await store.list()).length,2);
 const clock=await import('../apps/genesis/modules/scheduler/handler.mjs');
 clock.start(store);
 await clock.invoke('genesis.brains.autostep',
  {id:brain.id,steps_per_tick:2,stimulus:0.5},store);
 const tick0=(await store.load(brain.id)).ticks;
 await new Promise(r=>setTimeout(r,1250));
 const tick1=(await store.load(brain.id)).ticks;
 assert(tick1>=tick0+2,'background_clock_did_not_tick');
 await clock.invoke('genesis.brains.pause',{id:brain.id},store);
 const paused=(await store.load(brain.id)).ticks;
 await new Promise(r=>setTimeout(r,1150));
 assert.equal((await store.load(brain.id)).ticks,paused,'pause_did_not_stop_clock');
 assert.throws(()=>grow(brain,{count:100}),/growth_limit/);
 console.log('GENESIS_R01_OK',graph.nodes.length,'graph nodes');
}finally{await rm(root,{recursive:true,force:true});}
