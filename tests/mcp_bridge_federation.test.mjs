import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {auth,key,ext,createIdentity,open,close,addr,req,rpc,result,fakeCore,run,untilReady,pin} from './support/mcp_bridge_fixture.mjs';
test('impostor rejected, standby read only, migration requires explicitly promoted primary',async t=>{
 const owner=createIdentity(),impostor=createIdentity();
 const primary=await open(fakeCore('primary',['browser.tabs'],owner));
 const rogue=await open(fakeCore('impostor',['browser.tabs'],impostor));
 const migrated=await open(fakeCore('migrated',['browser.tabs'],owner));
 const reserve=await open(()=>{});const port=reserve.address().port;await close(reserve);
 const dir=await mkdtemp(join(tmpdir(),'ada-mcp-fed-')),path=join(dir,'registry.json');
 const cfg={schema:'adamantium.bridge.nodes.v1',nodes:[{id:'logical',approved:true,urls:[addr(primary)+'/'],tokenEnv:'ADA_TOKEN',allow:['browser.tabs'],identity:pin(owner)}]};
 await writeFile(path,JSON.stringify(cfg));
 const child=run({APP_PORT:String(port),ADA_INTERNAL_KEY:key,ADA_MCP_BEARER:ext,ADA_BRIDGE_CONFIG:path,ADA_TOKEN:auth});
 const url='http://127.0.0.1:'+port;
 t.after(async()=>{child.kill();await Promise.allSettled([close(primary),close(rogue),close(migrated)]);await rm(dir,{recursive:true,force:true});});
 await untilReady(url,child);
 assert.equal(result(await req(url,rpc(1,'tools/call',{name:'adamantium_invoke',arguments:{node_id:'logical',action:'browser.tabs'}}))).result.result.node,'primary');
 cfg.nodes[0].urls=[addr(rogue)+'/'];await writeFile(path,JSON.stringify(cfg));
 const spoof=await req(url,rpc(2,'tools/call',{name:'adamantium_invoke',arguments:{node_id:'logical',action:'browser.tabs'}}));
 assert.equal(spoof.payload.result.isError,true);assert.match(spoof.payload.result.content[0].text,/primary_unavailable/);
 cfg.nodes[0].urls=[addr(rogue)+'/',addr(migrated)+'/'];await writeFile(path,JSON.stringify(cfg));
 const standby=result(await req(url,rpc(3,'tools/call',{name:'adamantium_capabilities',arguments:{node_id:'logical'}})));
 assert.equal(standby.status,'reachable');assert.equal(standby.endpointIndex,1);
 const refused=await req(url,rpc(4,'tools/call',{name:'adamantium_invoke',arguments:{node_id:'logical',action:'browser.tabs'}}));
 assert.equal(refused.payload.result.isError,true);
 cfg.nodes[0].urls=[addr(migrated)+'/',addr(rogue)+'/'];await writeFile(path,JSON.stringify(cfg));
 const success=await req(url,rpc(5,'tools/call',{name:'adamantium_invoke',arguments:{node_id:'logical',action:'browser.tabs'}}));
 assert.equal(result(success).result.result.node,'migrated');
 cfg.nodes[0].identity=undefined;await writeFile(path,JSON.stringify(cfg));
 const unverified=result(await req(url,rpc(6,'tools/call',{name:'adamantium_nodes',arguments:{}})));
 assert.equal(unverified[0].status,'identity_unconfigured');
 const denied=await req(url,rpc(7,'tools/call',{name:'adamantium_invoke',arguments:{node_id:'logical',action:'browser.tabs'}}));
 assert.equal(denied.payload.result.isError,true);assert.match(denied.payload.result.content[0].text,/identity_pin_required/);
});
