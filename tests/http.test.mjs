import {strict as assert} from 'node:assert';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
const user=process.env.LOCALAPPDATA;
if(!user)throw Error('LOCALAPPDATA is required');
const auth=JSON.parse((await readFile(join(user,'Adamantium Toolbox','auth.json'),'utf8')).replace(/^\uFEFF/,''));
const base='http://127.0.0.1:8880';
async function get(path,headers={}){
 const res=await fetch(base+path,{headers,signal:AbortSignal.timeout(10000)});
 return {status:res.status,body:await res.json()};
}
const headers={Authorization:'Bearer '+auth.token};
const identityProbe=await get('/api/identity?challenge='+('a'.repeat(48)),headers);
assert.equal(identityProbe.status,200);
assert.equal(identityProbe.body.schema,'adamantium.core.identity.v1');
assert.equal(identityProbe.body.challenge,'a'.repeat(48));
assert.match(identityProbe.body.signature,/^[A-Za-z0-9+/]+={0,2}$/);
assert.equal((await get('/api/identity?challenge=bad',headers)).status,400);
assert.equal((await get('/api/identity?challenge='+('a'.repeat(48)))).status,401);
const health=await get('/health');
assert.equal(health.body.service,'Adamantium Toolbox');
assert.equal((await get('/api/semantic')).status,401);
assert.equal((await get('/api/changes/history')).status,401);
const backend=await get('/api/graph',headers);
assert.equal(backend.status,200);
assert(Array.isArray(backend.body.nodes));
const ir=await get('/api/semantic',headers);
assert.equal(ir.status,200);
assert.equal(ir.body.schema,'mas-semantic-ir-1');
const nav=await get('/api/navigation',headers);
assert.equal(nav.status,200);
assert.equal(nav.body.schema,'mas-linkfs-1');
const map=await get('/api/codemap?level=0',headers);
assert.equal(map.status,200);
assert.equal(map.body.schema,'mas-codemap-1');
assert(map.body.files.length>0);
const deps=await get('/api/codemap/graph',headers);
assert.equal(deps.status,200);
assert.equal(deps.body.schema,'mas-codegraph-1');
const source=deps.body.nodes.find(x=>x.file==='core/kernel.mjs');
assert(source);
const context=await get('/api/codemap/context?file=core%2Fkernel.mjs&sha='+source.sha256,headers);
assert.equal(context.status,200);
assert.equal(context.body.schema,'mas-context-pack-1');
assert(context.body.dependencies.includes('core/catalog.mjs'));
const mesh=await get('/api/mesh/status',headers);
assert.equal(mesh.status,200);
assert.equal(mesh.body.schema,'mas-mesh-status-1');
const history=await get('/api/changes/history',headers);
assert.equal(history.status,200);
console.log('HTTP_OK auth backend semantic linkfs codemap codegraph mesh history',backend.body.nodes.length,'nodes');
