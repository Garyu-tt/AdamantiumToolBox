import {strict as assert} from 'node:assert';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {validateManifest} from '../core/contract.mjs';
import {motors,synth,wav,RATE} from '../apps/mikoshi_phonetics/synth.mjs';
import {spectrum,distance} from '../apps/mikoshi_phonetics/spectrum.mjs';
import {initialize,imitate,evaluate} from '../apps/mikoshi_phonetics/learner.mjs';
const path=new URL('../apps/mikoshi_phonetics/manifest.json',import.meta.url);
const manifest=JSON.parse(await readFile(path,'utf8'));
assert(validateManifest(manifest));
const first=initialize(235),initialCopy=structuredClone(first);
const teacher=synth({f1:810,f2:1290},first.anchorHz);
assert.equal(teacher.length,2400);assert.equal(RATE,12000);
assert.equal(Buffer.from(wav(teacher),'base64').subarray(0,4).toString(),'RIFF');
assert.equal(spectrum(teacher).length,10);
const initial=evaluate(first,teacher);
const result=imitate(first,teacher);
assert(result.result.after<=initial.loss+1e-8);
assert(result.result.improved,'real acoustic error must decrease');
assert(result.result.after<initial.loss*.95,'synthetic lesson must measurably improve');
assert.equal(result.state.anchorHz,235);
assert.equal(result.state.lessons,1);
assert.deepEqual(first,initialCopy,'learning must not mutate source state');
assert(distance(spectrum(teacher),spectrum(synth(result.state.motor)))<
 distance(spectrum(teacher),spectrum(synth(first.motor))));
assert.throws(()=>motors({f1:800,f2:1000}),/invalid_formant/);
assert.throws(()=>spectrum([0,1]),/invalid_audio/);
assert.throws(()=>imitate({...first,anchorHz:600},teacher),/invalid_learning_state/);
assert.throws(()=>evaluate(first,Array(2048).fill(0)),/silent_audio/);
console.log('MIKOSHI_PHONETICS_OK measurable acoustic imitation, immutable voice anchor, WAV');
